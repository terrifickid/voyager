		<h2 id="cascade" class="font-display text-[28px] sm:text-[36px] mt-8 mb-2 leading-[1.1]">
			8. The thermodynamics of the cascade
		</h2>

		<p>
			The imperial machine requires a liquid surface: mobile, concentrated, cheap to tap. The cat's cradle converts that liquid surface into a solid lattice. Each transaction that settles locally instead of routing through a foreign correspondent account is a molecule that has crystallized. The machine cannot extract from what it cannot reach.
		</p>

		<p>Here is the cascade in thermodynamic terms.</p>

		<p>
			At 5% regional penetration, the imperial machine notices nothing. The mesh is a rounding error. The correspondent banking system still captures 95% of the flow, and its EROI remains strongly positive.
		</p>

		<p>
			At 15% penetration, the machine begins to feel friction. The mesh is large enough that some high-value corridors — artist payments, concierge bookings, cross-island commerce — are no longer routing through the center. The center's revenue per transaction in the region drops. It compensates by raising fees on the remaining 85%, which accelerates the conversion.
		</p>

		<p>
			At 30% penetration, the machine enters a danger zone. Its fixed overhead — compliance staff, legal entities, network fees — is now spread over a shrinking harvestable base. The EROI of operating in the region approaches one. The center faces a choice: subsidize the operation from other markets, or withdraw.
		</p>

		<p>
			At 50% penetration, the phase transition is complete. The mesh is now the default topology for regional economic activity. The imperial machine's EROI in the Caribbean is below one. It is metabolically unprofitable to run against the lattice. The machine does not collapse in a dramatic explosion; it simply stops expanding, stops investing, and stops setting the terms. The region has become, in the language of thermodynamics, a sink for imperial extraction and a source for local self-organization.
		</p>

		<p>
			This is the ratchet. Each conversion is structurally irreversible because the converted node has no reason to revert. The artist who can receive sats directly does not wake up one morning and decide they miss waiting five days for a wire transfer. The seller who settles instantly does not volunteer to resume paying 3.5% plus chargeback risk. The lattice is stable because it is the lower-energy state.
		</p>

		<p>
			The result is regional stabilization. As the mesh thickens, the Caribbean economy becomes less vulnerable to the policy changes, fee hikes, and de-platforming events of foreign-domiciled infrastructure. Local economic activity finds local routes. Capital circulates within the region instead of leaking outward as friction. The network effect is not merely defensive — it is regenerative. Each secure node makes the region more stable, and that stability attracts more nodes, which further hardens the lattice.
		</p>

