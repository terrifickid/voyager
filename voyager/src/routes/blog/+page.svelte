		<p>
			This essay is one argument. It runs from a wheat field in Sumer to a payment terminal in Barbados to a stake in the Carpathians. If you finish it, you will understand: why every empire in human history has the same logistical shape; why the way you break that shape has never changed; what the Caribbean has to do with a 15th-century Wallachian prince who burned his own crops rather than let an invading army feed on them; and why building on Voyager is, in thermodynamic terms, an act of refusal.
		</p>

		<p>
			If you only have thirty seconds, here is the conclusion in one paragraph: empires are machines for moving concentrated resources toward a center. They have always been this. They work because the fuel is cheap to gather. The way you stop them is not by fighting the army. It is by making the fuel impossible to gather cheaply. When the energy cost of extraction exceeds what extraction yields, the machine starves and either withdraws or collapses. The Caribbean sits inside a 21st-century version of this machine, where the concentrated fuel is regional economic activity and the imperial extractor is a foreign payment and identity stack. Voyager is one attempt to redesign the substrate so that fuel cannot be cheaply concentrated. Every app built on it thickens a mesh that, collectively, becomes too expensive to seize.
		</p>

		<p>The rest is the proof.</p>

