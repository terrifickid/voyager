		<h2 id="sargon" class="font-display text-[28px] sm:text-[36px] mt-8 mb-2 leading-[1.1]">
			1. Sargon of Akkad and the first imperial machine
		</h2>

		<p>
			Around 2334 BCE, a man named Sargon unified the city-states of Mesopotamia and built the first state most historians recognize as an empire. He did not invent taxation. City-temples had collected grain from farmers for centuries. What he invented was a machine for moving grain at scale. He built a capital at Akkad, dug canals, stationed a standing army, and routed tribute from every conquered city back to a single granary complex his own administrators controlled.
		</p>

		<p>
			The key move was not the army. The key move was the granary. A standing army that cannot eat does not stand. Sargon understood that his army was a thermodynamic system: every soldier burned calories, and those calories had to be physically delivered to him. The army was downstream of a logistical chain that started in a wheat field in Sumer, ran through a canal, ended in a silo in Akkad, and then ran back out to feed men who were doing nothing productive at the moment they were eating. They were projecting force. That is what imperial extraction systems do. They convert concentrated food into the projection of organized overhead so that more food can be concentrated next season.
		</p>

		<p>Two facts follow, and both of them are still true today.</p>

		<p>
			First, <strong>the standing bureaucracy is a net energy sink by design.</strong> It is paid in calories it does not earn. Its EROI is less than one. From the soldier's perspective, this is his salary. From the system's perspective, every calorie the army eats is a calorie that did not stay in the productive economy, and it must be replaced by next season's extraction. The overhead is a metabolic cost the center pays in order to perpetuate itself.
		</p>

		<p>
			Second, <strong>this only works while extraction remains cheaper than the cost of the overhead.</strong> If the friction of collecting, guarding, and transporting tribute exceeds the caloric return, the math breaks. Late Rome found this out at the edges of its grain catchment. The Maya found it out when the agricultural lowlands around their centers collapsed. Steppe states found it out the moment they left the grasslands their cavalry could graze. The imperial form stops being viable the moment its logistical EROI drops below one.
		</p>

		<p>
			That is the whole historical argument in one paragraph. Imperialism is thermodynamic. It is profitable to run only while concentrated surplus is cheap to seize. When the fuel becomes hard to centralize, the machine starves.
		</p>

		<hr class="my-4 border-0 h-px" style="background: var(--register-hair);" />

		<h2 id="vlad" class="font-display text-[28px] sm:text-[36px] mt-8 mb-2 leading-[1.1]">
			2. Vlad the Impaler and the oldest counter-imperial playbook
		</h2>

		<p>
			If Sargon is the template for the imperial extractor, then Vlad III of Wallachia, called Țepeș and remembered in the West as "the Impaler," is the template for the imperial resister. And his tactic is the inverse of Sargon's.
		</p>

		<p>
			In the winter of 1461–1462, Vlad fought a defensive war against Mehmed II, sultan of the Ottoman Empire — the largest centralized war machine on Earth at the time. He could not match it in men, cannons, or treasury. What he did was refuse to let it eat.
		</p>

		<p>
			Vlad's doctrine was, in modern language, total war waged against his own countryside rather than the invader. He ordered a scorched-earth retreat: every farm, every well, every grain store within reach of the advancing army was destroyed. Livestock were driven into fortified positions or killed. Crops were burned. The population was evacuated into the forests and mountain passes where the Ottoman cavalry could not maneuver. He poisoned the visible water sources. When the Ottoman vanguard entered the Wallachian lowlands, it found an empty landscape with no food and no water and no local guide willing to lead it deeper.
		</p>

		<p>
			Mehmed's army had two choices: starve where it stood, or retreat. It retreated.
		</p>

		<p>
			What this illustrates is the resource-denial theory of imperial defense, centuries before anyone gave it a name. You do not need to beat the empire in the field. You need to make the field empty. You do not win by killing soldiers. You win by killing the supply chain that feeds them. You concentrate nothing for the invader to capture. You disperse everything that would otherwise have been easy to seize. You raise the attacker's energy cost past the point at which the attack is worth running.
		</p>

		<p>
			Vlad had no EROI meter. He had no calculator. He had a peasant intuition: an army that cannot eat cannot advance. He raised the friction of empire until its logistical EROI went negative, and the empire withdrew.
		</p>

		<p>This is the playbook. Not because the technology has changed. Because the arithmetic has not.</p>

		<hr class="my-4 border-0 h-px" style="background: var(--register-hair);" />

		<h2 id="eroi" class="font-display text-[28px] sm:text-[36px] mt-8 mb-2 leading-[1.1]">
			3. EROI, the universal ratio
		</h2>

		<p>
			Energy Return on Investment is just two numbers in a fraction. How much energy did I get? How much energy did I spend to get it? If the second number is bigger, I am running an energy deficit. If the first is bigger, I have surplus.
		</p>

		<p>
			The ratio works on anything that burns energy. An oil well. A food forest. A foraging human. A state collecting tribute. A modern industrial supply chain. A merchant transaction. The scale does not matter. The ratio does.
		</p>

		<p>
			The reason this matters for the Caribbean is that the modern payment stack is the contemporary granary. It concentrates economic activity at low friction, taxes it, and uses a non-trivial slice of what it collects to fund the standing overhead of compliance: the legal entity, the KYC vendor, the regulator-relations team, the bank partnership manager, the card-network dispute apparatus, the chargeback reserve, the payout-cycle float. The system is designed to perpetuate itself, and the fuel it needs to perpetuate itself is your region's concentrated economic activity.
		</p>

		<p>
			The Caribbean is, in the language of the imperial machine, a high-friction catchment. The pricing you see — higher fees, longer settlement times, stricter documentation requirements, narrower eligibility — is the visible output of that calculation. The math is in the pricing. It is simply not published in a form you can read.
		</p>

		<p>
			The conceptual move, which is the whole point of this essay, is that the attack Vladed the Ottomans in 1462 is the same attack Voyager is built to enable in 2026. Make the concentrated fuel hard to gather. Make the imperial machine pay more energy than it gets back. Let the math do the defense.
		</p>

		<hr class="my-4 border-0 h-px" style="background: var(--register-hair);" />

		<h2 id="scattering" class="font-display text-[28px] sm:text-[36px] mt-8 mb-2 leading-[1.1]">
			4. "Scattering the granary" in 2026
		</h2>

		<p>
			The most durable protection is design, not decree. You do not protect a network from imperialism by passing a law against it. You protect it by making the network metabolically hostile to imperialism in the first place. Once the fuel cannot be cheaply concentrated, the imperial reactor loses the energy needed to sustain the complexity that defines it. Complexity flips from asset to liability, and the system either fragments, withdraws, or collapses under its own weight.
		</p>

		<p>
			A Caribbean payment stack today is concentrated. It runs through a small number of card networks, settles through correspondent accounts in US banks, and is gated by a handful of US-domiciled processors. The "fuel" — money, identity, reputation, contract — sits in a small number of high-density nodes a regulator can reach with one subpoena and a processor can gate with a policy change. The standing overhead is funded by your transaction fees. The EROI of the imperial machine against you is well above one, which is why it gets to set the terms.
		</p>

		<p>What does "scattering the granary" look like for a Caribbean-first internet?</p>

