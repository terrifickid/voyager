		<h2 id="conclusion" class="font-display text-[28px] sm:text-[36px] mt-8 mb-2 leading-[1.1]">
			9. The argument, stated one last time
		</h2>

		<p>
			Imperial systems run on concentrated surplus. They have since Sargon. The Caribbean in 2026 sits inside a 21st-century machine whose concentrated surplus is its economic activity and whose taxing entity is the foreign-domiciled payment and identity stack. The EROI of that machine against the Caribbean is currently positive, which is why it gets to set the terms.
		</p>

		<p>
			The structural literature is clear: you do not beat an imperial system by being better at its game. You beat it by making its game energetically unprofitable to run against you. The lever is design. The mechanism is the ratchet. The threshold, once crossed, is durable.
		</p>

		<p>
			Unseizable architecture — self-sovereign identity, peer-to-peer settlement, distributed discovery — is the lever. Each adoption event is a crystallization. Each crystallization thickens the mesh. Each thickening of the mesh raises the metabolic cost of imperial extraction until the machine's EROI against the region drops below one. The network effect then stabilizes the region: more secure nodes create a more secure network, and a secure network creates the conditions for local economic self-organization.
		</p>

		<p>
			The imperial machine's EROI against the Caribbean goes down each time a Caribbean node crystallizes. That is the same arithmetic as the granary, applied to a regional stack. It is the same arithmetic Vlad ran against Mehmed, applied to a digital substrate.
		</p>

		<p>
			We do not need to fight the system. We need to make operating against us expensive. The rest is metabolic.
		</p>

